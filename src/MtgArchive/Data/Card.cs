using System.Text.Json;

namespace MtgArchive.Data;

/// <summary>
/// One functional card in the corpus, keyed by Scryfall <c>oracle_id</c>
/// (unique) under a surrogate PK. Printings are deferred until collection
/// tracking — there are no printing tables. Typed columns cover everything
/// the index or derivations touch. The ingest phase computes every derived
/// value except <see cref="ColorIdentityMask"/>: the mask is a pure
/// re-encoding of <see cref="ColorIdentity"/> needing no Scryfall semantics,
/// so the database generates it and the two can never disagree; the flag
/// columns need keyword, type, and rules-text semantics only ingest sees.
///
/// The <c>*Contract</c> constants are the single authored copy of each
/// contract-bearing column's semantics; the model configuration writes them
/// to Postgres as <c>COMMENT ON COLUMN</c>.
/// </summary>
public sealed class Card
{
    public int Id { get; set; }

    /// <summary>Scryfall oracle_id — the functional card identity.</summary>
    public required Guid OracleId { get; set; }

    public required string Name { get; set; }

    /// <summary>Scryfall's <c>layout</c> ("normal", "modal_dfc",
    /// "transform", ...); null until an ingest fills it.</summary>
    public string? Layout { get; set; }

    public string? ManaCost { get; set; }

    /// <summary>Front-face mana value for multi-faced cards.</summary>
    public required decimal ManaValue { get; set; }

    /// <summary>Combined type line ("Front // Back" for multi-faced cards).</summary>
    public required string TypeLine { get; set; }

    public required string[] Supertypes { get; set; }

    public required string[] CardTypes { get; set; }

    public required string[] Subtypes { get; set; }

    public string? OracleText { get; set; }

    /// <summary>Card colors; null when only the faces carry colors.</summary>
    public string[]? Colors { get; set; }

    /// <summary>Whole-card color identity, readable form ("W".."G").</summary>
    public required string[] ColorIdentity { get; set; }

    public const string ColorIdentityMaskContract =
        "5-bit WUBRG bitmask the database generates from color_identity "
        + "(W=16, U=8, B=4, R=2, G=1); a deck-identity subset test is one "
        + "bitwise AND: color_identity_mask & ~deck_mask = 0.";

    /// <summary>Generated by the database per <see cref="ColorIdentityMaskContract"/>.</summary>
    public int ColorIdentityMask { get; private set; }

    public required string[] Keywords { get; set; }

    public string? Power { get; set; }

    public string? Toughness { get; set; }

    public string? Loyalty { get; set; }

    public string[]? ProducedMana { get; set; }

    public bool GameChanger { get; set; }

    public int? EdhrecRank { get; set; }

    public const string ReleasedAtContract =
        "First release date, stored so release-date exclusion can be added "
        + "later without schema change; pinned banlist versions do not "
        + "time-travel the card pool.";

    /// <summary>See <see cref="ReleasedAtContract"/>.</summary>
    public required DateOnly ReleasedAt { get; set; }

    public const string RawContract =
        "Latest Scryfall record only, kept for re-derivation; never a "
        + "historical snapshot — ingest diffs snapshots in flight.";

    /// <summary>See <see cref="RawContract"/>.</summary>
    public required JsonDocument Raw { get; set; }

    public const string CanBeCommanderContract =
        "Commander eligibility: legendary creature, or card text containing "
        + "\"can be your commander\"; never a meld result. Computed at ingest.";

    /// <summary>See <see cref="CanBeCommanderContract"/>.</summary>
    public bool CanBeCommander { get; set; }

    public const string CanBeBrawlCommanderContract =
        "Commander eligibility in the three Brawl formats: legendary creature, "
        + "legendary planeswalker, or legendary Vehicle or Spacecraft with power and "
        + "toughness (judged on the front face), or card text containing \"can be "
        + "your commander\"; never a meld result. Computed at ingest.";

    /// <summary>See <see cref="CanBeBrawlCommanderContract"/>.</summary>
    public bool CanBeBrawlCommander { get; set; }

    public const string IsMeldResultContract =
        "The combined back of a meld pair: Scryfall all_parts names the card "
        + "itself as the meld_result. Never a card of its own, so not legal in "
        + "any role. Computed at ingest.";

    /// <summary>See <see cref="IsMeldResultContract"/>.</summary>
    public bool IsMeldResult { get; set; }

    public const string DigitalOnlyContract =
        "A digital-only card, such as an Alchemy card: Scryfall digital is true "
        + "and the raw Scryfall legalities.commander value is not_legal. False when "
        + "either input is missing. Computed at ingest.";

    /// <summary>See <see cref="DigitalOnlyContract"/>.</summary>
    public bool DigitalOnly { get; set; }

    public const string HasPartnerContract =
        "The plain Partner keyword only — not Partner With, and not a named "
        + "Partner—variant (Friends forever, Survivors, …), which Scryfall "
        + "also lists under the \"Partner\" keyword.";

    /// <summary>See <see cref="HasPartnerContract"/>.</summary>
    public bool HasPartner { get; set; }

    public bool HasPartnerWith { get; set; }

    public bool HasFriendsForever { get; set; }

    public const string HasBackgroundContract =
        "Background mechanic, either side: a Background enchantment or a "
        + "commander with \"Choose a Background\".";

    /// <summary>See <see cref="HasBackgroundContract"/>.</summary>
    public bool HasBackground { get; set; }

    public bool HasDoctorsCompanion { get; set; }

    public const string CopyLimitContract =
        "Per-deck allowance: 1 default (singleton); NULL = unlimited (Basic "
        + "supertype or \"any number of cards named\" text); 7 for Seven Dwarves.";

    /// <summary>See <see cref="CopyLimitContract"/>.</summary>
    public int? CopyLimit { get; set; } = 1;

    public const string StaleContract =
        "Absent from the latest Oracle snapshot. Never deleted — excluded "
        + "from legal_candidates and search, retained so collection rows and "
        + "ban history never dangle.";

    /// <summary>See <see cref="StaleContract"/>.</summary>
    public bool Stale { get; set; }

    public List<CardFace> Faces { get; set; } = [];

    public List<CardRuling> Rulings { get; set; } = [];

    public List<CardOracleTag> OracleTags { get; set; } = [];

    /// <summary>One per face; empty while the card is stale.</summary>
    public List<CardFaceDocument> Documents { get; set; } = [];
}
